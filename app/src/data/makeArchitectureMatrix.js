// Resumen SIEMPRE derivado de MAKE_ARCHITECTURE_MATRIX — nunca escribir estos
// números a mano (mismo criterio que computeIntegracionResumen en
// makeCentroTecnicoLogic.js). Cualquier panel que muestre contadores del
// 50/50 debe llamar a esta función, no hardcodear cifras.
export function computeArchitectureResumen(matrix = MAKE_ARCHITECTURE_MATRIX) {
  const porEstado = {
    [MAKE_ARCH_ESTADOS.OPERATIONAL]: 0,
    [MAKE_ARCH_ESTADOS.PREPARED]: 0,
    [MAKE_ARCH_ESTADOS.EXTERNALLY_BLOCKED]: 0,
    [MAKE_ARCH_ESTADOS.PLANNED]: 0,
  };
  const porArea = {};
  let conInterfazCompleta = 0;
  let conContratoPreparado = 0;
  let probadosE2E = 0;
  let requierenWebhook = 0;

  for (const flujo of matrix) {
    porEstado[flujo.estado] = (porEstado[flujo.estado] || 0) + 1;
    porArea[flujo.area] = (porArea[flujo.area] || 0) + 1;
    if (flujo.tieneInterfazCompleta) conInterfazCompleta += 1;
    if (flujo.tieneContratoPreparado) conContratoPreparado += 1;
    if (flujo.probadoE2E) probadosE2E += 1;
    if (flujo.requiereWebhook) requierenWebhook += 1;
  }

  return {
    total: matrix.length,
    porEstado,
    porArea,
    conInterfazCompleta,
    conContratoPreparado,
    probadosE2E,
    requierenWebhook,
  };
}

// Devuelve solo las entradas de una área concreta, o todas si no se indica.
export function filterArchitectureMatrix(matrix, { area, estado, rol, requiereWebhook } = {}) {
  return matrix.filter((flujo) => {
    if (area && flujo.area !== area) return false;
    if (estado && flujo.estado !== estado) return false;
    if (rol && !flujo.rolesAutorizados.includes(rol)) return false;
    if (typeof requiereWebhook === "boolean" && flujo.requiereWebhook !== requiereWebhook) return false;
    return true;
  });
}
